// ============================================================
//  入力バリデーション（フロント側）
//  サーバー側の検証と同じ条件を、送信前にユーザーへ伝えるためのもの。
//  ※ サーバー側の検証を置き換えるものではない
// ============================================================

const Validate = {
  name(v) {
    if (!v) return 'お名前を入力してください。';
    if (v.length > 50) return 'お名前は50文字以内で入力してください。';
    return null;
  },
  email(v) {
    if (!v) return 'メールアドレスを入力してください。';
    // 過度に厳しくせず、明らかな誤りだけを弾く
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v)) {
      return 'メールアドレスの形式が正しくありません。';
    }
    return null;
  },
  password(v) {
    if (!v) return 'パスワードを入力してください。';
    if (v.length < 8) return 'パスワードは8文字以上で設定してください。';
    if (v.length > 72) return 'パスワードは72文字以内で入力してください。';
    return null;
  },
  role(v) {
    if (!['patient', 'caregiver'].includes(v)) {
      return 'ご利用の立場を選択してください。';
    }
    return null;
  },
};